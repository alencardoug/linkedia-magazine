#!/usr/bin/env node
// Generates src/types/contracts.d.ts from the v1 contracts/*.schema.json and src/types/contracts.v2.d.ts from the v2
// files (V2-05; separate modules because both define Block, Source…). D-029. Commit the output.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUTPUTS = {
  'contracts.d.ts': { article: 'Article', edition: 'Edition', tag_catalog: 'TagCatalog', theme_manifest: 'ThemeManifest' },
  'contracts.v2.d.ts': { 'article.v2': 'ArticleV2', 'edition.v2': 'EditionV2' },
};

for (const [outName, schemas] of Object.entries(OUTPUTS)) {
  const parts = ['/* Generated by `npm run gen:types` from contracts/*.schema.json. Do not edit. */\n'];
  for (const [file, name] of Object.entries(schemas)) {
    const schema = JSON.parse(readFileSync(join(ROOT, 'contracts', `${file}.schema.json`), 'utf8'));
    // Name the root type explicitly instead of deriving it from the schema title.
    const ts = await compile({ ...schema, title: name }, name, {
      bannerComment: '',
      additionalProperties: false,
      declareExternallyReferenced: true,
      style: { singleQuote: true, printWidth: 110 },
    });
    parts.push(`// contracts/${file}.schema.json\n${ts}`);
  }
  const out = join(ROOT, 'src', 'types', outName);
  writeFileSync(out, parts.join('\n'));
  console.log(`Gerado ${out}`);
}
