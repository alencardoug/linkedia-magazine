#!/usr/bin/env node
// Generates src/types/contracts.d.ts from contracts/*.schema.json (D-029). Commit the output.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SCHEMAS = { article: 'Article', edition: 'Edition', tag_catalog: 'TagCatalog', theme_manifest: 'ThemeManifest' };

const parts = ['/* Generated by `npm run gen:types` from contracts/*.schema.json. Do not edit. */\n'];
for (const [file, name] of Object.entries(SCHEMAS)) {
  const schema = JSON.parse(readFileSync(join(ROOT, 'contracts', `${file}.schema.json`), 'utf8'));
  // Name the root type explicitly instead of deriving it from the schema title.
  const ts = await compile({ ...schema, title: name }, name, {
    bannerComment: '',
    additionalProperties: false,
    declareExternallyReferenced: true,
    style: { singleQuote: true, printWidth: 110 },
  });
  parts.push(`// contracts/${file}.schema.json\n${ts}`);
}
const out = join(ROOT, 'src', 'types', 'contracts.d.ts');
writeFileSync(out, parts.join('\n'));
console.log(`Gerado ${out}`);
